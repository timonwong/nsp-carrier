const resources = {
  en: {app: en},
  'zh-CN': {app: zhCN},
} as const

export const i18n = createI18n(locale, {
  baseLocale: 'en',
  cache: resources,
  get: async (code) => resources[code],
})

export const messages = i18n('app', en)

export function setLocale(choice: LocaleChoice): void {
  localePreference.set(choice === 'system' ? undefined : choice)
}
